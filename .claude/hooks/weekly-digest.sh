#!/bin/bash
# Manual or scheduled maintenance script: aggregates the last 7 days of Session
# Handoffs (from Daily Notes/MMDDYY.md) into memory/weekly-digests/YYYY-MM-DD.md.
# Run weekly, by hand or from cron: bash .claude/hooks/weekly-digest.sh [--dry-run] [--days N]
#
# The digest has three parts: every handoff's Task and Next lines per day, a
# domain-activity count built from the keys in topic-routing.yml (when present),
# and every Decisions block from the week. Reading one digest instead of seven
# daily notes is how /retro, /memory-consolidate, and a returning session catch
# up on a week without loading it all into context.
# Never blocks, never edits a daily note, exits 0 when there is nothing to digest.

set -u

PROJECT_DIR="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}"
DAILY_DIR="$PROJECT_DIR/Daily Notes"
DIGEST_DIR="$PROJECT_DIR/memory/weekly-digests"
ROUTING="$PROJECT_DIR/.claude/hooks/topic-routing.yml"

DRY=0
DAYS=7
while [ "$#" -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1 ;;
    --days) shift; DAYS="${1:-7}" ;;
    -h|--help) sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  esac
  shift
done
case "$DAYS" in ''|*[!0-9]*) DAYS=7 ;; esac
[ "$DAYS" -lt 1 ] && DAYS=1

# Portable "N days ago" (BSD date on macOS, GNU date elsewhere).
days_ago() {
  date -v-"$1"d +"$2" 2>/dev/null || date -d "$1 days ago" +"$2" 2>/dev/null
}

END_DATE=$(date +"%Y-%m-%d")
START_DATE=$(days_ago $((DAYS - 1)) "%Y-%m-%d")
WEEK_FILE="$DIGEST_DIR/${END_DATE}.md"

if [ ! -d "$DAILY_DIR" ]; then
  echo "weekly-digest: no Daily Notes directory at $DAILY_DIR, nothing to digest."
  exit 0
fi

# Collect the daily notes that exist for the window, oldest first.
NOTES=()
I=$((DAYS - 1))
while [ "$I" -ge 0 ]; do
  DATE_FMT=$(days_ago "$I" "%m%d%y")
  NOTE="$DAILY_DIR/${DATE_FMT}.md"
  [ -f "$NOTE" ] && NOTES+=("$NOTE")
  I=$((I - 1))
done

if [ ${#NOTES[@]} -eq 0 ]; then
  echo "weekly-digest: no daily notes in the last $DAYS days, nothing to digest."
  exit 0
fi

# Topic keys from topic-routing.yml: top-level, uncommented, lowercase keys.
DOMAINS=""
if [ -f "$ROUTING" ]; then
  DOMAINS=$(grep -E '^[a-z"][a-z0-9" _-]*:[[:space:]]*$' "$ROUTING" | sed 's/:[[:space:]]*$//' | sed 's/"//g' | sort -u)
fi

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

{
  echo "# Weekly Digest: $START_DATE to $END_DATE"
  echo ""
  echo "Generated by weekly-digest.sh from ${#NOTES[@]} daily note(s). Source: the Session Handoff sections in \`Daily Notes/*.md\`."
  echo ""

  echo "## Sessions"
  echo ""
  for NOTE in "${NOTES[@]}"; do
    BASENAME=$(basename "$NOTE" .md)
    HANDOFF_COUNT=$(grep -c '^## Session Handoff' "$NOTE" 2>/dev/null | tr -d '[:space:]')
    HANDOFF_COUNT=${HANDOFF_COUNT:-0}
    [ "$HANDOFF_COUNT" = "0" ] && continue
    PLURAL=""
    [ "$HANDOFF_COUNT" -gt 1 ] && PLURAL="s"
    echo "### $BASENAME ($HANDOFF_COUNT handoff$PLURAL)"
    awk '/^## Session Handoff/{flag=1; next} flag && /^## /{flag=0} flag' "$NOTE" 2>/dev/null \
      | grep -E '^\*\*(Task|Next):\*\*' | head -20 | sed 's/^/  /'
    echo ""
  done

  if [ -n "$DOMAINS" ]; then
    echo "## Domain activity"
    echo ""
    echo "Days this week whose handoffs mention each topic from \`topic-routing.yml\`."
    echo ""
    FOUND=0
    while IFS= read -r DOMAIN; do
      [ -z "$DOMAIN" ] && continue
      COUNT=0
      for NOTE in "${NOTES[@]}"; do
        if awk '/^## Session Handoff/{flag=1} flag' "$NOTE" 2>/dev/null | grep -qiF "$DOMAIN"; then
          COUNT=$((COUNT + 1))
        fi
      done
      if [ "$COUNT" -gt 0 ]; then
        echo "- $DOMAIN: $COUNT day(s)"
        FOUND=1
      fi
    done <<< "$DOMAINS"
    [ "$FOUND" -eq 0 ] && echo "- (no registered topic appeared in this week's handoffs)"
    echo ""
  fi

  echo "## Decisions this week"
  echo ""
  ANY=0
  for NOTE in "${NOTES[@]}"; do
    BASENAME=$(basename "$NOTE" .md)
    DECISIONS=$(awk '/^\*\*Decisions:\*\*/{flag=1; next} flag && /^\*\*/{flag=0} flag' "$NOTE" 2>/dev/null | grep -v '^[[:space:]]*$' | head -20)
    if [ -n "$DECISIONS" ]; then
      echo "**$BASENAME:**"
      echo "$DECISIONS"
      echo ""
      ANY=1
    fi
  done
  [ "$ANY" -eq 0 ] && echo "(no Decisions blocks recorded this week)"
} > "$TMP"

if [ "$DRY" -eq 1 ]; then
  echo "weekly-digest: dry run, would write $WEEK_FILE"
  echo ""
  cat "$TMP"
  exit 0
fi

mkdir -p "$DIGEST_DIR"
cp "$TMP" "$WEEK_FILE"
echo "weekly-digest: written to $WEEK_FILE (${#NOTES[@]} daily note(s), $START_DATE to $END_DATE)"
exit 0
